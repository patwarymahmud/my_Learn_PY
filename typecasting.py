# Python Type Casting
# =========================================================
# Type Casting মানে হলো
# এক data type কে অন্য data type এ convert করা।
# Python এ সবচেয়ে গুরুত্বপূর্ণ casting:
# bool()
# int()
# float()
# list()
# tuple()
# type()

# =========================================================
# 1. Boolean Casting
# =========================================================
# Boolean Casting মানে হলো
# কোনো value কে True অথবা False এ convert করা।
# bool() function ব্যবহার করা হয়।

# ---------------------------------------------------------
# Example 1
# ---------------------------------------------------------
print(bool(1))
# Output:
# True
# কারণ:
# 1 এর ভিতরে value আছে।

# ---------------------------------------------------------
# Example 2
# ---------------------------------------------------------
print(bool(0))
# Output:
# False
# কারণ:
# 0 হলো False value।

# ---------------------------------------------------------
# Example 3
# ---------------------------------------------------------
print(bool("Hello"))
# Output:
# True
# কারণ:
# string খালি না।

# ---------------------------------------------------------
# Example 4
# ---------------------------------------------------------
print(bool(""))
# Output:
# False
# কারণ:
# Empty string False হয়।

# ---------------------------------------------------------
# Example 5
# ---------------------------------------------------------
print(bool([1, 2, 3]))
# Output:
# True
# কারণ:
# list এর ভিতরে item আছে।

# ---------------------------------------------------------
# Example 6
# ---------------------------------------------------------
print(bool([]))
# Output:
# False
# কারণ:
# Empty list False হয়।

# =========================================================
# Real Life Example
# =========================================================
shopping = ["rice", "oil"]
print(bool(shopping))
# Output:
# True
# কারণ:
# shopping list খালি না।

shopping2 = []
print(bool(shopping2))
# Output:
# False
# কারণ:
# list খালি।

# =========================================================
# সহজে মনে রাখো
# =========================================================
# Value থাকলে → True
# Empty হলে → False

# =========================================================
# 2. Float to Integer Casting
# =========================================================
# int() ব্যবহার করে float কে integer বানানো হয়।
# decimal অংশ কেটে যায়।

# ---------------------------------------------------------
# Example
# ---------------------------------------------------------
x = 5.9
print(int(x))
# Output:
# 5
# কারণ:
# decimal .9 remove হয়েছে।

# ---------------------------------------------------------
# Another Example
# ---------------------------------------------------------
y = 10.99
print(int(y))
# Output:
# 10

# =========================================================
# Real Life Example
# =========================================================
price = 99.99
print(int(price))
# Output:
# 99
# কারণ:
# decimal বাদ গেছে।

# =========================================================
# সহজে মনে রাখো
# =========================================================
# int() = decimal কেটে integer বানায়

# =========================================================
# 3. Integer to Float Casting
# =========================================================
# float() ব্যবহার করে integer কে float বানানো হয়।
# অর্থাৎ decimal যোগ হয়।

# ---------------------------------------------------------
# Example
# ---------------------------------------------------------
x = 10
print(float(x))
# Output:
# 10.0

# ---------------------------------------------------------
# Another Example
# ---------------------------------------------------------
y = 25
print(float(y))
# Output:
# 25.0

# =========================================================
# Real Life Example
# =========================================================
age = 20
print(float(age))
# Output:
# 20.0
# কারণ:
# integer কে decimal number বানানো হয়েছে।

# =========================================================
# সহজে মনে রাখো
# =========================================================
# float() = integer কে decimal number বানায়

# =========================================================
# 4. List Casting
# =========================================================
# list() ব্যবহার করে অন্য data type কে list বানানো হয়।

# ---------------------------------------------------------
# Example
# ---------------------------------------------------------
x = (1, 2, 3)
print(list(x))
# Output:
# [1, 2, 3]
# কারণ:
# tuple কে list এ convert করা হয়েছে।

# =========================================================
# Real Life Example
# =========================================================
marks = (80, 90, 100)
print(list(marks))
# Output:
# [80, 90, 100]

# =========================================================
# সহজে মনে রাখো
# =========================================================
# list() = data কে list বানায়

# =========================================================
# 5. Tuple Casting
# =========================================================
# tuple() ব্যবহার করে data কে tuple বানানো হয়।

# ---------------------------------------------------------
# Example
# ---------------------------------------------------------
x = [1, 2, 3]
print(tuple(x))
# Output:
# (1, 2, 3)
# কারণ:
# list কে tuple এ convert করা হয়েছে।

# =========================================================
# Real Life Example
# =========================================================
shopping = ["rice", "oil", "milk"]
print(tuple(shopping))
# Output:
# ('rice', 'oil', 'milk')

# =========================================================
# সহজে মনে রাখো
# =========================================================
# tuple() = data কে tuple বানায়

# =========================================================
# 6. Type Check
# =========================================================
# type() ব্যবহার করে
# কোনো variable এর data type দেখা হয়।

# ---------------------------------------------------------
# Example
x = 10
print(type(x))
# Output:
# <class 'int'>

# ---------------------------------------------------------
# Another Example
# ---------------------------------------------------------
name = "Mahamud"
print(type(name))
# Output:
# <class 'str'>

# ---------------------------------------------------------
# Another Example
# ---------------------------------------------------------
price = 99.5
print(type(price))
# Output:
# <class 'float'>

# =========================================================
# Real Life Example
# =========================================================
data = [1, 2, 3]
print(type(data))
# Output:
# <class 'list'>

# =========================================================
# সহজে মনে রাখো
# =========================================================
# type() = data type check করে

# =========================================================
# সবচেয়ে Important মনে রাখার জিনিস
# =========================================================
# bool()  = True অথবা False বানায়
# int()   = decimal কেটে integer বানায়
# float() = integer কে decimal number বানায়
# list()  = data কে list বানায়
# tuple() = data কে tuple বানায়
# type()  = data type check করে

