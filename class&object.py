# সহজ বাস্তব উদাহরণে Python Class & Object
# ধরো তুমি একটা মোবাইল কোম্পানি খুলছো 📱
# এখন মোবাইল বানানোর আগে একটা ডিজাইন / নকশা লাগে।
# সেই ডিজাইনেই লেখা থাকে:
# - ফোনের রং কী হবে
# - কী কী কাজ করবে
# - কেমন দেখতে হবে
# এই ডিজাইন / নকশাকেই Python এ বলে Class বা Blueprint।
class Mobile:
    color = "Black"

    def call(self):
        print("Calling...")

# এখন এই ডিজাইন দেখে আসল মোবাইল বানানো হচ্ছে।
# Python এ এই আসল মোবাইলগুলোকেই বলে Object।
m1 = Mobile()
m2 = Mobile()

print(m1.color)
m1.call()

# সহজ ভাষায়:
# Class = Blueprint / Design / নকশা
# Object = সেই নকশা দিয়ে বানানো আসল জিনিস
# যেমন:
# মোবাইলের ডিজাইন = Class
# আসল মোবাইল = Object
# এক Class থেকে অনেক Object তৈরি করা যায়।