# =========================================
# Built-in Functions
# =========================================

# min()  -> সবচেয়ে ছোট সংখ্যা বের করে
# max()  -> সবচেয়ে বড় সংখ্যা বের করে
# sum()  -> সব সংখ্যা যোগ করে
# abs()  -> ঋণাত্মক (-) চিহ্ন বাদ দেয়
# pow()  -> Power হিসাব করে
# round() -> কাছের পূর্ণসংখ্যায় রাউন্ড করে

# =========================================
# min()
# =========================================

a = (min(10, 5, 20, 2))
print(a)
# Output:
# 2

# =========================================
# max()
# =========================================

b = (max(10, 5, 20, 2))
print(b)
# Output:
# 20

# =========================================
# sum()
# =========================================

numbers = [10, 20, 30]

d = (sum(numbers))
print(d)
# Output:
# 60

# =========================================
# abs()
# =========================================

c = (abs(-10))
print(c)
# Output:
# 10

# abs() ঋণাত্মক চিহ্ন বাদ দিয়ে দেয়।
#
# Example:
#
# abs(-50) = 50
# abs(-100) = 100

# =========================================
# pow()
# =========================================

A = (pow(2, 3))
print(A)
# Output:
# 8

# কারণ:
#
# 2 × 2 × 2 = 8

# একই কাজ:

print(2 ** 3)

# Output:
# 8

# =========================================
# round()
# =========================================

print(round(4.3))

# Output:
# 4

print(round(4.7))

# Output:
# 5

# Beginner Rule:
#
# 0.0 - 0.4 -> নিচে নামবে
#
# 0.5 - 0.9 -> উপরে উঠবে

# Example:
#
# 4.1 -> 4
# 4.2 -> 4
# 4.3 -> 4
# 4.4 -> 4
#
# 4.5 -> 5
# 4.6 -> 5
# 4.7 -> 5
# 4.8 -> 5
# 4.9 -> 5

# =========================================
# Math Module
# =========================================

import math

# =========================================
# math.sqrt()
# =========================================

print(math.sqrt(25))

# Output:
# 5

# sqrt = Square Root
#
# অর্থ:
#
# কোন সংখ্যাকে নিজে দিয়ে গুণ করলে
# মূল সংখ্যাটি পাওয়া যায়।

# Example:
#
# 5 × 5 = 25
#
# তাই:
#
# √25 = 5

print(math.sqrt(81))

# Output:
# 9

# কারণ:
#
# 9 × 9 = 81

# =========================================
# math.ceil()
# =========================================

print(math.ceil(4.1))

# Output:
# 5

print(math.ceil(4.9))

# Output:
# 5

# ceil() সবসময় উপরের পূর্ণসংখ্যায় নিয়ে যায়।
#
# মনে রাখো:
#
# Ceiling = ছাদ
#
# তাই সবসময় উপরে যাবে।

# Example:
#
# 4.1 -> 5
# 4.5 -> 5
# 4.9 -> 5

# =========================================
# math.floor()
# =========================================

print(math.floor(4.9))

# Output:
# 4

print(math.floor(4.1))

# Output:
# 4

# floor() সবসময় নিচের পূর্ণসংখ্যায় নিয়ে যায়।
#
# মনে রাখো:
#
# Floor = মেঝে
#
# তাই সবসময় নিচে যাবে।

# Example:
#
# 4.1 -> 4
# 4.5 -> 4
# 4.9 -> 4

# =========================================
# math.pi
# =========================================

print(math.pi)

# Output:
# 3.141592653589793

# π (Pi) একটি বিশেষ গণিতের সংখ্যা।
#
# π ≈ 3.14159

# এখানে:
#
# ≈ = প্রায় সমান

# π পাওয়া যায়:
#
# বৃত্তের পরিধি ÷ ব্যাস

# Formula:
#
# π = Circumference / Diameter

# =========================================
# Circle Example
# =========================================

# ধরো:
#
# Radius = 3

r = 3

# Diameter

d = 2 * r

# d = 6

# -----------------------------------------

# Circumference

# C = 2 × π × r

# C = 2 × 3.14159 × 3
#
# C = 18.85

# -----------------------------------------

# Area

# A = π × r²

# A = 3.14159 × 3²
#
# A = 3.14159 × 9
#
# A = 28.27

# -----------------------------------------

# r² মানে:
#
# r × r

# Example:
#
# 3² = 3 × 3 = 9
#
# 5² = 5 × 5 = 25

# =========================================
# math.e (Euler Number)
# =========================================

print(math.e)

# Output:
# 2.718281828459045

# e ≈ 2.71828

# এটি একটি বিশেষ গণিতের সংখ্যা।

