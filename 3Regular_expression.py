import re

# ----------------------------------------------------------
# 1. Email Pattern
# ----------------------------------------------------------

pattern = r"\w+@\w+\.\w+"

# Example:
text = "hasan@gmail.com"

print(re.findall(pattern, text))

# Output:
# ['hasan@gmail.com']

# Explanation:
#
# \w+   → username part (hasan)
# @     → symbol
# \w+   → domain (gmail)
# \.    → dot (.)
# \w+   → extension (com)

# Meaning:
# email format match করছে

# ==========================================================

# ----------------------------------------------------------
# 2. Phone Number (11 Digit)
# ----------------------------------------------------------

pattern = r"\d{11}"

text = "01712345678"

print(re.findall(pattern, text))

# Output:
# ['01712345678']

# Explanation:
#
# \d   → digit (0-9)
# {11} → ঠিক 11টা সংখ্যা লাগবে

# Meaning:
# 11 digit phone number match করছে

# ==========================================================

# ----------------------------------------------------------
# 3. OTP (6 Digit Code)
# ----------------------------------------------------------

pattern = r"\d{6}"

text = "123456"

print(re.findall(pattern, text))

# Output:
# ['123456']

# Explanation:
#
# \d   → digit
# {6}  → ঠিক 6টা digit

# Meaning:
# OTP code match করছে

# ==========================================================

# ----------------------------------------------------------
# 4. Username
# ----------------------------------------------------------

pattern = r"\w+"

text = "hasan_123"

print(re.findall(pattern, text))

# Output:
# ['hasan_123']

# Explanation:
#
# \w = letter + number + underscore
# +  = এক বা একাধিক character

# Meaning:
# username valid format match করছে

# ==========================================================

# ----------------------------------------------------------
# 5. Password এ Number আছে কিনা
# ----------------------------------------------------------

pattern = r"\d"

text = "mypassword1"

print(re.findall(pattern, text))

# Output:
# ['1']

# Explanation:
#
# \d = শুধু digit খুঁজে
#
# তাই password-এর মধ্যে যদি number থাকে
# তাহলে সেটাকে ধরবে

# Meaning:
# password এ সংখ্যা আছে কিনা check করা

