# python join two list
list1 = ["a", "b", "c"]
list2 = [4, 5, 6]
list3 = list1 + list2
print(list3)
# Output:
# ['a', 'b', 'c', 4, 5, 6]
# এবার extent method ব্যবহার করে প্রফেশনালি এক লাইনে কিভাবে করতে হয় তার example দেখব
list1.extend(list2)
print(list1)
# Output:
#['a', 'b', 'c', 4, 5, 6]
# এখানে চাইলে প্রথম লিস্টে letter এবং দ্বিতীয় লিস্টে নাম্বার থাকলে এভাবেও এটাতে জয়েন করা যায় যেমন লেটার আর নাম্বার একসাথে জয়েন হয়ে যাবে

# ==================================================
# Python count() Method
# ==================================================

# count()
# = কোনো Value কয়বার আছে গুনে

# ------------------------
# String Example
# ------------------------

text = "banana"

print(text.count("a"))

# Output:
# 3

# ------------------------
# List Example
# ------------------------

numbers = [10, 20, 10, 30, 10]

print(numbers.count(10))

# Output:
# 3

# ------------------------
# Range Example
# ------------------------

text = "banana"

print(text.count("a", 2, 6))

# Output:
# 2

# Syntax:
#
# object.count(value)
#
# object.count(value,start,end)

# One Line:
#
# count()
# = কয়বার পাওয়া গেছে সেটা গুনে
