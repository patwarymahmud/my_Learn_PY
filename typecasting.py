#Python type casting
# পাইথনে Type Casting মানে হলো এক data type কে অন্য data type এ convert করা।
# যেমন:
# string → integer
# integer → float
# float → string
# ইত্যাদি।

# সব type সব type এ convert হয় না।
# সহজে মনে রাখো
# | Function  | কাজ                   |
# | --------- | --------------------- |
# | `int()`   | integer বানায়        |
# | `float()` | decimal number বানায় |
# | `str()`   | string বানায়         |
# | `bool()`  | boolean বানায়        |

# Integer Casting
x = "20"
y = int(x)

print(y)
print(type(y))


# Float Casting
a = "3.5"
b = float(a)

print(b)
print(type(b))


# String Casting
m = 100
n = str(m)

print(n)
print(type(n))

# Boolean Casting
# বুলিয়ান কাস্টিং এর ভিতরে কোন ভেরিয়েবল মান যদি একদম জিরো হয় কিবা না থাকে তাহলে সেটা false  হবে আর যদি বেরিয়ে ফেল এর মান থাকে যেমন এর থেকে শুরু হয় তাহলে সেটা True হবে 
p = 0
q = bool(p)

print(q)
print(type(q))

